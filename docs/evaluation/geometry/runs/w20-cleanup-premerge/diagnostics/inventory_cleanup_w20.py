def git(*a: str, cwd: Path = ROOT, check: bool = True) -> str:
    return subprocess.run(["git", *a], cwd=cwd, capture_output=True, text=True, encoding="utf-8",
                          errors="replace", check=check).stdout


def gitb(*a: str, cwd: Path = ROOT) -> bytes:
    return subprocess.run(["git", *a], cwd=cwd, capture_output=True, check=True).stdout


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def rel(p: Path) -> str:
    try:
        return p.relative_to(ROOT).as_posix()
    except ValueError:
        return p.as_posix()


