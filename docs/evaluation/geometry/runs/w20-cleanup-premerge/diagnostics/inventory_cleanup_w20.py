def legacy() -> list[dict]:
    ra = []
    tracked = sorted(git("ls-files", rel(LEGACY)).split())
    assert sorted(f"docs/legacy/superpowers/{k}" for k in LEGACY_CLASS) == tracked, "legacy table out of date"
    for f in tracked:
        k = f.removeprefix("docs/legacy/superpowers/")
        lop, ly, ky = LEGACY_CLASS[k]
        ref = [r for r in git("grep", "-l", "-F", Path(f).name, "--", ".", f":!{f}", check=False).split() if r]
        song = [r for r in ref if not r.startswith("docs/evaluation/") and not r.startswith("docs/legacy/")]
        live = {s: sum(int(x.rsplit(":", 1)[1]) for x in git("grep", "-c", "-F", s, "--", "backend/app", "frontend/src",
                                                                check=False).split() if ":" in x) for s in ky}
        assert all(live.values()), (f, live)
        ra.append({"area": "docs/legacy/superpowers", "path": f, "class": lop, "reason": ly,
                   "sha256": sha(ROOT / f), "lines": len((ROOT / f).read_text(encoding="utf-8").splitlines()),
                   "referenced_by_living": song, "referenced_by_frozen_or_legacy": sorted(set(ref) - set(song)),
                   "live_symbols_hits": live, "action": "KEEP"})
    return ra


