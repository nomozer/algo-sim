def _goi_review(p: Path) -> tuple[bool, str]:
    a, b = p.name.removeprefix("review-").removesuffix(".diff").split("..")
    goc = p.read_bytes()
    for ab in ("7", "8"):
        g = ["-c", f"core.abbrev={ab}"]
        dau = (b"## Commits\n" + gitb(*g, "log", "--oneline", f"{a}..{b}") + b"\n## Files changed\n"
               + gitb(*g, "diff", "--stat", f"{a}..{b}") + b"\n## Diff\n" + gitb(*g, "diff", "-U10", f"{a}..{b}"))
        for tieu_de in (f"{a}..{b}", f"{a}..HEAD"):
            if goc == f"# Review package: {tieu_de}\n\n".encode() + dau:
                return True, f"regenerated byte for byte (core.abbrev={ab}, title {tieu_de})"
    return False, "not regenerated byte for byte"


def _brief(p: Path, ke_hoach: dict[str, set[str]]) -> tuple[bool, str]:
    dong = [x for x in p.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").split("\n") if x.strip()]
    ten, trung = max(((k, sum(1 for x in dong if x in v)) for k, v in ke_hoach.items()), key=lambda t: t[1])
    return trung == len(dong), f"{trung}/{len(dong)} non-empty lines in {ten}"


def superpowers() -> list[dict]:
    ke_hoach = {f"docs/legacy/superpowers/plans/{p.name}": set(x for x in p.read_text(encoding="utf-8").replace(
        "\r\n", "\n").split("\n") if x.strip()) for p in sorted((LEGACY / "plans").glob("*.md"))}
    ra = []
    for p in sorted(x for x in SP.rglob("*") if x.is_file()):
        r = rel(p)
        muc = {"area": ".superpowers", "path": r, "bytes": p.stat().st_size}
        if p in NOT_OPENED:
            muc |= {"class": "REVIEW_REQUIRED", "reason": "brainstorm server token: not opened", "action": "KEEP"}
        elif re.fullmatch(r"review-[0-9a-f]{7,8}\.\.[0-9a-f]{7,8}\.diff", p.name):
            ok, ly = _goi_review(p)
            muc |= {"sha256": sha(p), "class": "REPRODUCIBLE_TEMP_SAFE_TO_DELETE" if ok else "REVIEW_REQUIRED",
                    "reason": f"review package; {ly}", "action": "DELETE" if ok else "KEEP"}
        elif p.parent == SP / "sdd" and p.name.endswith("-brief.md"):
            ok, ly = _brief(p, ke_hoach)
            muc |= {"sha256": sha(p), "class": "DUPLICATE_SAFE_TO_DELETE" if ok else "REVIEW_REQUIRED",
                    "reason": f"task brief; {ly}" + ("" if ok else " — carries lines found in no committed plan"),
                    "action": "DELETE" if ok else "KEEP"}
        elif r.startswith(".superpowers/sdd/w20-cleanup-premerge/"):
            muc |= {"class": "KEEP_ACTIVE", "reason": "this wave's ledger", "action": "KEEP"}
        elif r == ".superpowers/sdd/w19-docs-organization/CLAUDE.md.before-w19":
            muc |= {"class": "KEEP_ACTIVE", "reason": "verbatim copy of the user's local CLAUDE.md before W19 (revert copy)",
                    "action": "KEEP"}
        elif r == ".superpowers/sdd/.gitignore":
            muc |= {"class": "KEEP_ACTIVE", "reason": "workspace infrastructure", "action": "KEEP"}
        elif r.startswith(".superpowers/sdd/curried-splashing-finch/") and p.name.endswith("-brief.md"):
            muc |= {"class": "KEEP_ARCHITECTURAL_HISTORY", "action": "KEEP",
                    "reason": "W14/W15 task brief; the W14 plan file was overwritten by the W15 plan, so these briefs are "
                              "the only copy of the W14 plan text"}
        else:
            loai = ("ledger" if p.name.startswith("progress") else "subagent or close report" if "report" in p.name
                    else "test or tool log" if p.suffix in (".log", ".txt") else "UI brainstorm draft or server state"
                    if "brainstorm" in r else "plan copy or pointer" if "plan" in p.name.lower() or p.name.endswith("BRIEF.txt")
                    else "uncommitted diff" if p.suffix == ".diff" else "agent artifact")
            muc |= {"class": "REVIEW_REQUIRED", "action": "KEEP",
                    "reason": f"{loai}: content not verified to exist elsewhere; the folder is git-ignored, so a deletion "
                              "could not be undone"}
        ra.append(muc)
    return ra


# ── D:/tmp (bounded) ──────────────────────────────────────────────────────────────────────────────────────────────
_CACHE_DIRS = re.compile(r"(^|/)(__pycache__|\.pytest_cache|node_modules|dist)/$|\.db$")


def tmp() -> list[dict]:
    doi_tuong = {}
    for dong in git("rev-list", "--all", "--objects").splitlines():
        h, _, duong = dong.partition(" ")
        if duong:
            doi_tuong.setdefault(h, duong)
    ra = []
    for p in sorted(TMP.iterdir()):
        muc = {"area": "D:/tmp", "path": p.as_posix()}
        if p in NOT_OPENED:
            muc |= {"class": "REVIEW_REQUIRED", "reason": "settings backup: not opened (SENSITIVE_NOT_READ)", "action": "KEEP"}
        elif p.is_file():
            muc["bytes"] = p.stat().st_size
            hs = {git("hash-object", "--no-filters", str(p)).strip(), git("hash-object", "--path=x.txt", str(p)).strip()}
            co = sorted(h for h in hs if h in doi_tuong)
            if p.stat().st_size == 0:
                muc |= {"sha256": sha(p), "class": "DUPLICATE_SAFE_TO_DELETE", "reason": "empty file: carries no information",
                        "action": "DELETE"}
            elif co:
                c = git("log", "--all", "-1", "--format=%H", f"--find-object={co[0]}").strip()
                muc |= {"sha256": sha(p), "class": "DUPLICATE_SAFE_TO_DELETE", "action": "DELETE",
                        "reason": f"bytes equal blob {co[0]}, reachable at {doi_tuong[co[0]]}",
                        "recover": f"git show {c}:{doi_tuong[co[0]]}"}
            else:
                muc |= {"class": "REVIEW_REQUIRED", "reason": "UNKNOWN_EARLIER_WAVE: bytes match no reachable blob", "action": "KEEP"}
        elif (p / ".git").is_dir():
            head = git("rev-parse", "HEAD", cwd=p).strip()
            refs = [x.split() for x in git("for-each-ref", "--format=%(objectname) %(refname)", cwd=p).splitlines()]
            thieu = [r for h, r in refs if subprocess.run(["git", "cat-file", "-e", f"{h}^{{commit}}"], cwd=ROOT,
                                                         capture_output=True).returncode != 0]
            stash = git("stash", "list", cwd=p).strip()
            doi = git("--no-optional-locks", "status", "--porcelain", cwd=p).strip()
            bo = [x[3:] for x in git("--no-optional-locks", "status", "--porcelain", "--ignored", cwd=p).splitlines()
                  if x.startswith("!! ")]
            la = [x for x in bo if not _CACHE_DIRS.search(x)]
            ok = (subprocess.run(["git", "cat-file", "-e", f"{head}^{{commit}}"], cwd=ROOT).returncode == 0
                  and not thieu and not stash and not doi and not la)
            muc |= {"class": "REPRODUCIBLE_TEMP_SAFE_TO_DELETE" if ok else "REVIEW_REQUIRED", "head": head,
                    "refs": len(refs), "refs_missing_here": thieu, "stash": bool(stash), "changes": bool(doi),
                    "ignored": bo, "ignored_not_cache": la, "action": "DELETE" if ok else "KEEP",
                    "reason": "full clone of this repository: HEAD and every ref exist here, no stash, no change, only "
                              "caches and a sqlite file ignored" if ok else "clone with content not proven reproducible",
                    "recover": f"git worktree add --detach <dir> {head}"}
        else:
            muc |= {"class": "REVIEW_REQUIRED", "reason": "UNKNOWN_EARLIER_WAVE: folder, not a clone of this repository",
                    "action": "KEEP"}
        ra.append(muc)
    return ra


