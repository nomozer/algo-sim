def main() -> None:
    if OUT.exists():
        raise SystemExit(f"refusing to overwrite {OUT}")
    muc = legacy() + superpowers() + tmp() + W19_OUTSIDE
    dem: dict = {}
    for m in muc:
        d = dem.setdefault(m["area"], {})
        d[m["class"]] = d.get(m["class"], 0) + 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({
        "schema_version": "w20-cleanup-inventory/1", "measured_at_commit": git("rev-parse", "HEAD").strip(),
        "classes": ["KEEP_ACTIVE", "KEEP_ARCHITECTURAL_HISTORY", "KEEP_RESEARCH_EVIDENCE", "DUPLICATE_SAFE_TO_DELETE",
                    "ABANDONED_OUT_OF_SCOPE_SAFE_TO_DELETE", "REPRODUCIBLE_TEMP_SAFE_TO_DELETE", "REVIEW_REQUIRED"],
        "not_opened": sorted(p.as_posix() for p in NOT_OPENED),
        "counts": dem, "delete_candidates": sum(1 for m in muc if m["action"] == "DELETE"), "items": muc,
    }, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(dem, ensure_ascii=False, indent=1))
    print("delete candidates:", sum(1 for m in muc if m["action"] == "DELETE"))


if __name__ == "__main__":
    main()
